"""scanner/baseline_init.py — Generate stub baseline entries from a prior run.

Python port of ``scanner/scan_baseline_init.sh``. Reads a prior scan's
``aggregate/combined.sarif`` (produced by :mod:`scanner.aggregate`) and
emits one stub entry per (check_id, resource) pair into the consumer's
``pci_baseline.yaml``.

Stub semantics
--------------
Stubs have ``TBD`` for ``justification``, ``owner``, ``ticket_id``, and
``expires_on``. The aggregator enforces the rule:

    suppress iff (owner != "TBD") AND (expires_on >= today)

so stubs NEVER suppress findings. They show up in ``report.html`` under
a "requires triage" banner until the team populates the real values.

This is a pure file-rewrite operation; no Azure mutations, no terraform.

Console scripts
---------------
* ``pacioli baseline init <run_dir>`` → :func:`main` (preferred)
"""
