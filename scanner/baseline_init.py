# ---------------------------------------------------------------------------

DEFAULT_TOP_N: int = 50

# Header preserved verbatim when appending to an existing baseline file.
# Mirrors the bash version's `if not header.startswith("#"): ...` branch.
DEFAULT_HEADER: str = (
    "# PCI baseline -- repo-wide suppressions for known/accepted findings.\n"
    "# Generated by `pacioli baseline init`.\n"
    "# See docs/runbooks/pci-checkov.md for triage workflow.\n"
    "#\n"
    "# Entries with TBD owner/ticket/expires_on DO NOT suppress findings.\n"
    "# Triage top-N by hit_count: populate justification, owner, ticket_id,\n"
    "# expires_on. The aggregator stops suppressing the entry if expires_on\n"
    "# is in the past OR owner == TBD.\n"
)


# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------


class BaselineInitError(RuntimeError):
    """Raised on unrecoverable baseline-init failure (e.g. SARIF missing)."""


# ---------------------------------------------------------------------------
# SARIF → stub-entry conversion
# ---------------------------------------------------------------------------


def _resolve_uri(result: dict) -> str:
    """Return the physicalLocation URI of a SARIF result, else ``""``.

    Pure data-shaping helper. Pulled out so ``_collect_stub_pairs`` stays
    focused on the dedup loop, not on nested ``[0].get(...).get(...)``.
    """
    locs = result.get("locations") or []
    if not locs:
        return ""
    first = locs[0] or {}
    phys = first.get("physicalLocation", {}) or {}
    artifact = phys.get("artifactLocation", {}) or {}
    return artifact.get("uri", "") or ""


def _collect_stub_pairs(sarif_data: dict) -> dict[tuple[str, str], dict[str, set]]:
    """Dedup SARIF results into ``(check_id, uri) -> {projects, envs}`` buckets.

    Walks every run/result in ``sarif_data`` and accumulates the
    ``(pci_project, pci_env)`` tuples that produced each
    ``(ruleId, physicalLocation.uri)`` pair. Pair with no project or env
    metadata still receives a bucket so the stub survives.
    """
    seen: dict[tuple[str, str], dict[str, set]] = defaultdict(
        lambda: {"projects": set(), "envs": set()}
    )

    for run in sarif_data.get("runs", []) or []:
        props = run.get("properties", {}) or {}
        project = props.get("pci_project", "") or ""
        env = props.get("pci_env", "") or ""

        for result in run.get("results", []) or []:
            check_id = result.get("ruleId", "UNKNOWN") or "UNKNOWN"
            uri = _resolve_uri(result)
            bucket = seen[(check_id, uri)]
            if project:
                bucket["projects"].add(project)
            if env:
                bucket["envs"].add(env)

    return seen


def _entry_to_yaml(check_id: str, uri: str, bucket: dict[str, set], today: str) -> dict:
    """Build one stub YAML dict from a single SARIF bucket.

    Mirrors the dict literal in scan_baseline_init.sh lines 80-95. The
    ``hit_count`` falls back to ``1`` when no project/env metadata was
    attached to the bucket — those findings still need a stub so the
    team can triage them.
    """
    projects = bucket["projects"]
    envs = bucket["envs"]
    has_metadata = bool(projects or envs)

    return {
        "check_id": check_id,
        "resource_pattern": uri or "*",
        "justification": "TBD",
        "compensating_control": "TBD",
        "owner": "TBD",
        "ticket_id": "TBD",
        "expires_on": "TBD",
        "first_seen": sorted(f"{p}/{e}" for p in projects for e in envs),
        "hit_count": len(projects) * len(envs) if has_metadata else 1,
        # Bonus metadata: generation timestamp so re-runs can be
        # detected by downstream tooling.
        "generated_at": today,
    }


def _build_stub_entries(combined_sarif: Path, top_n: int) -> list[dict]:
    """Read combined.sarif and return one stub dict per (check_id, resource).

    Mirrors the inline ``python <<'PY'`` block in scan_baseline_init.sh
    lines 67-103: dedupe by (ruleId, physicalLocation.artifactLocation.uri),
    collect the (project, env) tuples per pair, sort by hit_count desc.

    Args:
        combined_sarif: Path to ``<run_dir>/aggregate/combined.sarif``.
        top_n: Reserved for the run-book reference (the bash script prints
            "triage the top $TOP entries by hit_count" but still emits a
            stub for every distinct (check, resource) pair). Kept here
            for CLI parity.

    Returns:
        List of stub dicts ready to be YAML-serialized into
        ``pci_baseline.yaml``.
    """
    del top_n  # see docstring — every distinct pair gets a stub

    if not combined_sarif.is_file():
        raise BaselineInitError(f"combined.sarif not found: {combined_sarif}")

    try:
        data = json.loads(combined_sarif.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise BaselineInitError(f"failed to parse {combined_sarif}: {exc}") from exc

    pairs = _collect_stub_pairs(data)
    today = date.today().isoformat()

    out = [
        _entry_to_yaml(check_id, uri, bucket, today)
        for (check_id, uri), bucket in pairs.items()
    ]
    out.sort(key=lambda x: (-x["hit_count"], x["check_id"], x["resource_pattern"]))
    return out


# ---------------------------------------------------------------------------
# Baseline-file I/O
# ---------------------------------------------------------------------------


def _read_existing_header(baseline_path: Path) -> str:
    """Return the header lines (everything before ``suppressions:``).

    Mirrors scan_baseline_init.sh lines 131-137. If the file doesn't
    exist or has no header lines, returns an empty string and the caller
    will prepend :data:`DEFAULT_HEADER`.
    """
    if not baseline_path.is_file():
        return ""
    try:
        text = baseline_path.read_text(encoding="utf-8")
    except OSError:
        return ""
    header_lines: list[str] = []
    for line in text.splitlines():
        if line.startswith("suppressions:"):
            break
        header_lines.append(line)
    return "\n".join(header_lines).rstrip()


def _load_existing_suppressions(baseline_path: Path) -> list[dict]:
    """Return the ``suppressions`` list from an existing baseline file, or [].

    Mirrors scan_baseline_init.sh line 108. Returns ``[]`` on any parse
    failure so ``--append`` degrades gracefully.
    """
    if not baseline_path.is_file():
        return []
    try:
        data = yaml.safe_load(baseline_path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return []
    if not isinstance(data, dict):
        return []
    suppr = data.get("suppressions") or []
    return [s for s in suppr if isinstance(s, dict)]


def _merge_append(
    existing: list[dict], new_entries: list[dict]
) -> list[dict]:
    """Merge new entries into existing, dedup by (check_id, resource_pattern).

    Mirrors scan_baseline_init.sh lines 121-129.
    """
    seen = {(e.get("check_id"), e.get("resource_pattern")) for e in existing}
    merged = list(existing)
    for entry in new_entries:
        key = (entry.get("check_id"), entry.get("resource_pattern"))
        if key not in seen:
            merged.append(entry)
            seen.add(key)
    return merged


def _validate_safe_path(path: Path, allowed_roots: list[Path]) -> Path:
    """Ensure ``path`` resolves under one of ``allowed_roots``.

    Guards the file-write sinks (S2083). The CLI accepts ``--baseline``
    from the user (and via ``$PACIOLI_BASELINE_FILE`` /
    ``$PACIOLI_TARGET_REPO`` / ``$PCI_REPO_ROOT``), so a symlink or
    ``..`` traversal could redirect the write outside the consumer's
    intended location. Resolving and checking against an allow-list
    catches that.

    Args:
        path: Caller-supplied destination path (not yet trusted).
        allowed_roots: Canonical roots the write is permitted to land
            under. Typically ``Path.home()`` (for the
            ``~/.pacioli/config.yaml`` family) and ``Path.cwd()``
            (for ``<run-dir>/pci_baseline.yaml`` style destinations).

    Returns:
        The resolved absolute ``Path`` on success.

    Raises:
        PathResolutionError: If the resolved path is not under any
            allowed root.
    """
    resolved = path.expanduser().resolve()
    for root in allowed_roots:
        canonical_root = root.expanduser().resolve()
        if resolved == canonical_root or canonical_root in resolved.parents:
            return resolved
    raise PathResolutionError(
        f"refusing to write outside allow-listed roots: {resolved} "
        f"not under {[str(r) for r in allowed_roots]}"
    )


def _write_baseline_file(
    safe_path: Path,
    header: str,
    body: str,
    entry_count: int,
) -> int:
    """Persist the rendered baseline payload to ``safe_path``.

    This sink accepts ONLY a pre-validated ``safe_path`` (the result of
    :func:`_validate_safe_path`), which keeps the S2083 surface tiny:
    every caller that does file I/O has to pass through the allow-list
    check first. Returns the entry count for the caller's bookkeeping.
    """
    safe_path.write_text(header + "\n\n" + body, encoding="utf-8")
    return entry_count


def _write_baseline(
    baseline_path: Path,
    entries: list[dict],
    *,
    append: bool,
) -> int:
    """Write the baseline file. Returns the number of entries written.

    Mirrors scan_baseline_init.sh lines 112-157. Preserves the existing
    comment header when present.

    The destination is validated against an allow-list of roots before
    any file operation runs. This guards against S2083 (user-controlled
    path flowing into a file write).
    """
    # Resolve against the allow-list BEFORE any path operation so a
    # symlink / ``..`` traversal in ``--baseline`` cannot redirect the
    # write outside the consumer's intended location (S2083).
    safe_path = _validate_safe_path(
        baseline_path,
        allowed_roots=[Path.home(), Path.cwd()],
    )

    if append:
        existing = _load_existing_suppressions(safe_path)
        merged = _merge_append(existing, entries)
    else:
        merged = list(entries)

    header = _read_existing_header(safe_path)
    if not header.lstrip().startswith("#"):
        header = DEFAULT_HEADER.rstrip()

    payload = {
        "version": 1,
        "verified_against": date.today().isoformat(),
        "suppressions": merged,
    }

    safe_path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    # ``safe_path`` was produced by ``_validate_safe_path`` above; the
    # allow-list check confirms it resolves under an approved root, so
    # the write below cannot escape the consumer's intended location.
    return _write_baseline_file(safe_path, header, body, len(merged))


