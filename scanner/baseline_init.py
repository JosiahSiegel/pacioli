def _resolve_run_dir(run_dir: Optional[str]) -> Path:
    """Locate the run dir. Mirrors scan_baseline_init.sh lines 48-55.

    Falls back to the most recent ``~/.pacioli/runs/<id>/`` (analog of
    the bash version's ``ls -td "${PCI_REPO_ROOT}/.checkov"/*/``). When
    no run dir exists, raise :class:`BaselineInitError`.
    """
    if run_dir:
        path = Path(run_dir).expanduser().resolve()
        if not path.is_dir():
            raise BaselineInitError(f"run dir not found: {path}")
        return path

    # Default: most-recent under ~/.pacioli/runs/.
    runs_root = Path.home() / ".pacioli" / "runs"
    if runs_root.is_dir():
        candidates = sorted(
            (p for p in runs_root.iterdir() if p.is_dir()),
            key=lambda p: p.stat().st_mtime,
            reverse=True,
        )
        if candidates:
            return candidates[0].resolve()

    raise BaselineInitError(
        f"no run dir found under {runs_root}; pass --run-dir explicitly"
    )


def _resolve_target_baseline(args: argparse.Namespace) -> Path:
    """Locate the destination baseline file.

    Priority: ``--baseline`` > ``$PACIOLI_BASELINE_FILE`` > ``$PACIOLI_TARGET_REPO/pci_baseline.yaml``
    > ``$PCI_REPO_ROOT/pci_baseline.yaml`` > ``./pci_baseline.yaml`` (cwd).

    Mirrors the bash version's ``$PCI_BASELINE_FILE`` defaulting chain.
    """
    cli_value = getattr(args, "baseline", None)
    if cli_value:
        return Path(cli_value).expanduser().resolve()

    env_value = os.environ.get("PACIOLI_BASELINE_FILE", "").strip()
    if env_value:
        return Path(env_value).expanduser().resolve()

    for env_name in ("PACIOLI_TARGET_REPO", "PCI_REPO_ROOT"):
        repo = os.environ.get(env_name, "").strip()
        if repo:
            candidate = Path(repo).expanduser() / "pci_baseline.yaml"
            return candidate.resolve()

    return (Path.cwd() / "pci_baseline.yaml").resolve()


def _log(level: str, msg: str) -> None:
    """Emit a scan.sh-style ``pci_log`` line to stderr."""
    print(f"{level}  {msg}", file=sys.stderr, flush=True)


def main(argv: Optional[Iterable[str]] = None) -> int:
    """CLI entry point for ``pacioli baseline init``.

    Mirrors scan_baseline_init.sh. Returns process exit code:
        0   success
        2   run dir / SARIF missing
        64  invalid arguments
    """
    ap = argparse.ArgumentParser(
        prog="pacioli-baseline-init",
        description=(
            "Generate stub baseline entries from a prior scan's combined.sarif. "
            "Stubs require manual triage (TBD owner/justification/expires_on) "
            "before the aggregator will treat them as suppressions."
        ),
    )
    ap.add_argument(
        "--run-dir",
        default=None,
        help="Run dir produced by `pacioli scan` (default: most recent under ~/.pacioli/runs/).",
    )
    ap.add_argument(
        "--baseline",
        default=None,
        help="Destination baseline YAML (default: $PACIOLI_BASELINE_FILE or <target_repo>/pci_baseline.yaml).",
    )
    ap.add_argument(
        "--top",
        type=int,
        default=DEFAULT_TOP_N,
        help="Run-book reference count (every distinct (check_id, resource) still gets a stub).",
    )
    ap.add_argument(
        "--append",
        action="store_true",
        help="Merge with existing pci_baseline.yaml (default: replace).",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="Print intended actions without writing the baseline file.",
    )
    args = ap.parse_args(list(argv) if argv is not None else None)

    try:
        run_dir = _resolve_run_dir(args.run_dir)
    except BaselineInitError as exc:
        _log("ERROR", str(exc))
        return 2

    combined_sarif = run_dir / "aggregate" / "combined.sarif"
    target_baseline = _resolve_target_baseline(args)

    _log("INFO", f"source:  {combined_sarif}")
    _log("INFO", f"target:  {target_baseline}")

    if args.dry_run:
        _log("INFO", "(dry-run) baseline file not written")
        return 0

    try:
        entries = _build_stub_entries(combined_sarif, args.top)
    except BaselineInitError as exc:
        _log("ERROR", str(exc))
        return 2

    if not entries:
        _log("WARN", f"no findings in {combined_sarif}; baseline unchanged")
        return 0

    try:
        n = _write_baseline(target_baseline, entries, append=args.append)
    except OSError as exc:
        _log("ERROR", f"failed to write {target_baseline}: {exc}")
        return 1

    _log("INFO", f"wrote {n} entries to {target_baseline}")
    _log("INFO", f"baseline initialized; triage the top {args.top} entries by hit_count")
    return 0


if __name__ == "__main__":
    sys.exit(main())