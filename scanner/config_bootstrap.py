class ScopeInitError(RuntimeError):
    """Raised on unrecoverable scaffolding failure."""


# ---------------------------------------------------------------------------
# Env helpers (mirror scanner.mapping_picker._is_truthy_env)
# ---------------------------------------------------------------------------


def _is_truthy_env(name: str) -> bool:
    """Return True when env var ``name`` is set to a truthy value.

    Mirrors :func:`scanner.mapping_picker._is_truthy_env` so the
    non-interactive gate is consistent across both interactive modules.
    """
    value = os.environ.get(name)
    if value is None:
        return False
    return value.strip().lower() in _TRUTHY_ENV


