"""scanner/config_bootstrap.py -- Interactive scope+baseline scaffold for first-time users.

Auto-creates ``pci_scope.yaml`` and ``pci_baseline.yaml`` when missing, mirroring the
mapping picker pattern. Reuses :func:`scanner.discovery.discover_pairs` for framework-
agnostic IaC discovery. Reuses :func:`scanner.baseline_init._validate_safe_path` and
:func:`scanner.baseline_init._is_under` for S2083-safe writes. Never overwrites
existing files.

Interaction model
-----------------

The CLI dispatcher calls :func:`is_bootstrap_interactive` to decide whether the
interactive prompt may run. When interactive, :func:`prompt_and_create` prints a
``Y/n`` prompt; when non-interactive, :func:`auto_create` writes silently. Both
respect the "never overwrite" contract: existing files are always skipped.

Discovery model
---------------

:func:`render_scope_yaml` calls :func:`scanner.discovery.discover_pairs` and groups
the returned ``(project, env)`` pairs into the ``projects:`` list of the scope YAML.
When the target repo is empty (``NoIaCFoundError``), the scope falls back to
``scan_paths: [{path: "."}]`` so the user can still run a scan.

Safety model
------------

Every file write goes through :func:`scanner.baseline_init._validate_safe_path`
with an allow-list of ``Path.home()``, ``Path.cwd()``, and the temp directory,
matching the pattern established by :func:`scanner.baseline_init._write_baseline_file`.
This guards against S2083 (user-controlled path flowing into a file write).
"""

